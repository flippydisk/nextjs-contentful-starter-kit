import fs from 'node:fs';
import path from 'node:path';
import { Debug } from '@flippydisk/tools';

const rootDir = process.cwd();
const themeDir = path.join(rootDir, 'src', 'themes');
const debug = new Debug({ control: 'GenerateTheme', debug: false });
const themes = ['rocket', 'atlas'];

const sharedInputFiles = [
    path.join(themeDir, 'all', '_mixins.scss'),
    path.join(themeDir, 'all', '_tokens.scss')
];

const stripLocalImports = (contents) => {
    return contents
        .replace(/^\s*@import\s+['"]\.\.\/all\/_mixins\.scss['"];\s*$/gm, '')
        .replace(/^\s*@import\s+['"]\.\.\/all\/_tokens\.scss['"];\s*$/gm, '')
        .replace(/^\s*@use\s+['"]\.\.\/all\/_mixins\.scss['"]\s+as\s+\*\s*;\s*$/gm, '')
        .replace(/^\s*@use\s+['"]\.\.\/all\/_tokens\.scss['"]\s+as\s+\*\s*;\s*$/gm, '')
        .trim();
};

const getThemeInputFiles = themeName => [
    ...sharedInputFiles,
    path.join(themeDir, themeName, 'theme.scss'),
    path.join(themeDir, themeName, 'layout.scss')
];

const generateTheme = (themeName) => {
    const outputFile = path.join(themeDir, themeName, 'generated.scss');
    const inputFiles = getThemeInputFiles(themeName);
    const sections = [
        '// This file is generated by bin/generate-theme.js.',
        `// Edit the source theme files under src/themes/${themeName} instead.`,
        '@use \'../all/_mixins.scss\' as *;',
        '@use \'../all/_tokens.scss\' as *;'
    ];

    for (const inputFile of inputFiles.slice(2)) {
        const relativePath = path.relative(rootDir, inputFile).replaceAll('\\', '/');
        const contents = stripLocalImports(fs.readFileSync(inputFile, 'utf8'));
        sections.push(`/* Source: ${relativePath} */`);
        sections.push(contents);
    }

    const nextOutput = `${sections.join('\n\n')}\n`;
    const previousOutput = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : null;

    if (previousOutput !== nextOutput) {
        fs.writeFileSync(outputFile, nextOutput);
        debug.info(`Updated ${path.relative(rootDir, outputFile).replaceAll('\\', '/')}`);
    }
};

const generateThemes = () => {
    for (const themeName of themes) {
        generateTheme(themeName);
    }
};

const watchTheme = () => {
    generateThemes();

    const inputFiles = [...new Set(themes.flatMap(getThemeInputFiles))];

    for (const inputFile of inputFiles) {
        fs.watchFile(inputFile, { interval: 250 }, () => {
            generateThemes();
        });
    }

    debug.info('Watching theme source files for changes...');
};

if (process.argv.includes('--watch')) {
    watchTheme();
} else {
    generateThemes();
}
